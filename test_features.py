import os
import sys
import json
import ast

print("=" * 55)
print("     FREQTRADE FUNCTIONAL FEATURE TESTS")
print("=" * 55)

results = []

# --- TEST 1: run.py launcher ---
print("\n[TEST 1] Verifying run.py launcher...")
if os.path.exists("run.py"):
    try:
        with open("run.py") as f:
            ast.parse(f.read())
        print("  PASS: run.py exists and is valid Python syntax.")
        results.append(("run.py - Valid Python", True))
    except SyntaxError as e:
        print(f"  FAIL: run.py has a syntax error: {e}")
        results.append(("run.py - Valid Python", False))
else:
    print("  FAIL: run.py not found!")
    results.append(("run.py - Found", False))

# --- TEST 2: user.cfg ---
print("\n[TEST 2] Verifying user.cfg configuration...")
if os.path.exists("user.cfg"):
    try:
        with open("user.cfg") as f:
            cfg = json.load(f)
        print("  PASS: user.cfg is valid JSON.")
        results.append(("user.cfg - Valid JSON", True))

        exchange = cfg.get("exchange", {})
        api_server = cfg.get("api_server", {})
        pairs = exchange.get("pair_whitelist", [])

        checks = [
            ("exchange name set", bool(exchange.get("name"))),
            ("dry_run is set", "dry_run" in cfg),
            ("stake_currency set", bool(cfg.get("stake_currency"))),
            ("api_server enabled", api_server.get("enabled") is True),
            ("whitelist has pairs", len(pairs) > 0),
        ]
        for label, passed in checks:
            status = "PASS" if passed else "FAIL"
            print(f"  {status}: {label}")
            results.append((f"user.cfg - {label}", passed))

        print(f"\n  Config Summary:")
        print(f"    Exchange     : {exchange.get('name')}")
        print(f"    Dry Run      : {cfg.get('dry_run')}")
        print(f"    Stake Amount : {cfg.get('stake_amount')} {cfg.get('stake_currency')}")
        print(f"    Max Trades   : {cfg.get('max_open_trades')}")
        print(f"    API Server   : {api_server.get('enabled')}")
        print(f"    Pairs ({len(pairs)})   :")
        for p in pairs:
            print(f"      -> {p}")
    except json.JSONDecodeError as e:
        print(f"  FAIL: user.cfg is not valid JSON: {e}")
        results.append(("user.cfg - Valid JSON", False))
else:
    print("  FAIL: user.cfg not found!")
    results.append(("user.cfg - Found", False))

# --- TEST 3: user_data directory structure ---
print("\n[TEST 3] Verifying user_data directory structure...")
dirs = [
    "user_data",
    "user_data/strategies",
    "user_data/data",
    "user_data/logs",
    "user_data/backtest_results",
]
for d in dirs:
    exists = os.path.isdir(d)
    status = "PASS" if exists else "FAIL"
    print(f"  {status}: {d}")
    results.append((f"Dir: {d}", exists))

# --- TEST 4: SampleStrategy file ---
print("\n[TEST 4] Verifying SampleStrategy file...")
strategy_path = os.path.join("user_data", "strategies", "SampleStrategy.py")
if os.path.exists(strategy_path):
    try:
        with open(strategy_path) as f:
            ast.parse(f.read())
        print(f"  PASS: SampleStrategy.py found and is valid Python.")
        results.append(("SampleStrategy - Valid Python", True))
    except SyntaxError as e:
        print(f"  FAIL: SampleStrategy.py has a syntax error: {e}")
        results.append(("SampleStrategy - Valid Python", False))
else:
    print("  WARN: SampleStrategy.py not found (will be auto-generated by run.py on first launch).")
    results.append(("SampleStrategy - Found", None))

# --- TEST 5: Downloaded market data ---
print("\n[TEST 5] Verifying downloaded market data...")
data_dir = os.path.join("user_data", "data", "binance")
if os.path.isdir(data_dir):
    files = [f for f in os.listdir(data_dir) if f.endswith(".feather") or f.endswith(".json")]
    print(f"  PASS: Data directory found with {len(files)} data file(s).")
    for fn in files[:8]:
        print(f"    -> {fn}")
    if len(files) > 8:
        print(f"    ... and {len(files) - 8} more.")
    results.append(("Market data downloaded", len(files) > 0))
else:
    print(f"  WARN: No data directory found at {data_dir}.")
    results.append(("Market data downloaded", False))

# --- TEST 6: Freqtrade config validation ---
print("\n[TEST 6] Validating user.cfg via Freqtrade config loader...")
try:
    import subprocess
    result = subprocess.run(
        ["uv", "run", "freqtrade", "show-config", "--config", "user.cfg"],
        capture_output=True, text=True, timeout=20
    )
    if result.returncode == 0:
        print("  PASS: Freqtrade accepted user.cfg as a valid configuration.")
        results.append(("Freqtrade config validation", True))
    else:
        print("  FAIL: Freqtrade rejected user.cfg!")
        print(f"  Error: {result.stderr[-300:]}")
        results.append(("Freqtrade config validation", False))
except Exception as e:
    print(f"  FAIL: Could not run freqtrade: {e}")
    results.append(("Freqtrade config validation", False))

# --- Summary ---
print()
print("=" * 55)
print("                 SUMMARY")
print("=" * 55)
passed = sum(1 for _, r in results if r is True)
failed = sum(1 for _, r in results if r is False)
warned = sum(1 for _, r in results if r is None)
for label, r in results:
    if r is True:
        print(f"  [PASS] {label}")
    elif r is False:
        print(f"  [FAIL] {label}")
    else:
        print(f"  [WARN] {label}")
print()
print(f"  Total: {passed} passed, {failed} failed, {warned} warnings")
print("=" * 55)
